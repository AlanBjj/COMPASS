"""Write configs/<backbone>/<dataset>.yaml (COMPASS) and configs/<backbone>/baselines/<dataset>.yaml.

Every config uses the backbone served by vLLM (scripts/serve.sh), the local Qwen3-32B judge, and the
frozen web-search snapshot with BM25. The COMPASS configs hold the full method; an ablation is chosen
at run time with `python -m compass.run --variant <ablation>`, which only switches that component off.

    python scripts/make_configs.py
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# name -> (served model name, vLLM port, extra model keys)
BACKBONES = {
    "qwen3-8b": ("qwen3-8b", 8100, "enable_thinking: false, "),
    "llama-3.1-8b": ("llama-3.1-8b-instruct", 8101, ""),
    "ministral-8b": ("ministral-8b-instruct", 8102, ""),
}
JUDGE = ("{base_url: http://localhost:8200/v1, model: qwen3-32b, local: true, enable_thinking: false, "
         "temperature: 0.0, max_tokens: 512, request_timeout: 120}")

# The FreshQA release in data/freshqa/freshqa.json is dated by its own answers ("What month is it?"
# -> April; next full moon -> May 1, 2026), i.e. April 2026. Only FreshQA asks time-relative
# questions, so only its runs get the date (every method, baselines included).
CURRENT_DATE = {"freshqa": "April 2026"}

DATASETS = {
    # name -> (path, backbone max_tokens)
    "truthfulqa": ("data/truthfulqa/TruthfulQA.json", 1024),
    "gsm8k": ("data/gsm8k/test.jsonl", 2048),
    "strategyqa": ("data/strategyqa/strategyqa.json", 1024),
    "freshqa": ("data/freshqa/freshqa.json", 1024),
}

TEMPLATE = """# COMPASS on {ds} with the {backbone} backbone (local Qwen3-32B judge, frozen snapshot retrieval).
# Generated by scripts/make_configs.py; edit that script, not this file. These settings are the full
# method; `python -m compass.run --variant <ablation>` switches one component off (compass.run.ABLATIONS).
run:
  name: compass
  seed: 0
  sample_size: null
  checkpoint_every: 100{run_extra}

models:
  controller: {{base_url: http://localhost:{port}/v1, model: {served}, {extra}temperature: 0.0, max_tokens: 1024}}
  backbone:   {{base_url: http://localhost:{port}/v1, model: {served}, {extra}temperature: 0.0, max_tokens: {max_tokens}}}
  judge:      {judge}

client: {{concurrency: 16, retries: 3}}
gate: {{alpha: 0.4, tau: 0.55}}
decompose: {{min_subqueries: 2, max_subqueries: 4}}
scoring: {{acc_weight: 0.6, rel_weight: 0.4, low_quality_threshold: 2.0}}
rag:
  backend: local_snapshot
  corpus: data/snapshot_corpus/corpus.jsonl
  index_dir: data/snapshot_corpus/bm25
  per_source_k: 5
  source_weights: {{official: 0.45, news: 0.35, academic: 0.20}}
  query_rewrite: {{enabled: true, n_queries: 3, per_source_k: 6}}

# Type-routed consistency: TRACE votes (math, yes/no) and CPC (open-ended answers).
trace: {{enabled: true, k: 5, temperature: 0.7, math: true, reasoning: true, fact: false, cpc_temperature: 0.0, cpc_max_tokens: 256, yesno_robust_parse: true, yesno_majority: true, yesno_min_ballots: 3, cpc_require_agreement: false, early_stop: true}}
# Planner and consistency rules (see compass/pipeline.py).
rules: {{entity_retrieval: true, math_no_split: true, yesno_facts: true, cpc_on_retrieval: true, recency_retrieval: true, fallback_retrieval: true, arith_fix: true, no_cpc_recency: true, fact_no_split: true, rag_knowledge_fallback: false, grounded_audit: false}}

dataset: {{name: {ds}, path: {path}, split: dev, dev_size: 100}}
output: {{dir: results/{backbone}}}
"""

BASELINE_TEMPLATE = """# Baselines on {ds} with the {backbone} backbone: the same backbone, judge, retrieval corpus and
# benchmark date as COMPASS in configs/{backbone}/{ds}.yaml. Generated by scripts/make_configs.py.
run:
  name: baselines
  seed: 0
  sample_size: null
  checkpoint_every: 100{run_extra}

models:
  backbone: {{base_url: http://localhost:{port}/v1, model: {served}, {extra}temperature: 0.0, max_tokens: 2048}}
  judge:    {judge}

client: {{concurrency: 16, retries: 3}}

# Per-baseline hyperparameters (faithful to the official implementations; adaptations are
# documented in each module of compass/baselines/). Pick the method with `--method`.
methods:
{methods}
retrieval: {{backend: local_snapshot, corpus: data/snapshot_corpus/corpus.jsonl, index_dir: data/snapshot_corpus/bm25, num_results: 5}}

dataset: {{name: {ds}, path: {path}, split: dev, dev_size: 100}}
output: {{dir: results/{backbone}/baselines}}
"""

# TARG / DTR thresholds per backbone and dataset, calibrated on the dev split with
# scripts/calibrate_gate.py --rep 1 2 3. 1e9 = never retrieve (rho 0 was best), -1.0 = always (rho 1).
# tau depends on the model's uncertainty scale, so every backbone is calibrated separately.
TARG_TAU = {
    "qwen3-8b": {"truthfulqa": 0.165117, "gsm8k": 1e9, "strategyqa": 1e9, "freshqa": -1.0},
    "llama-3.1-8b": {"truthfulqa": 0.362762, "gsm8k": 1e9, "strategyqa": 0.441668, "freshqa": -1.0},
    "ministral-8b": {"truthfulqa": -1.0, "gsm8k": 1e9, "strategyqa": 1e9, "freshqa": -1.0},
}
DTR_TAU = {
    "qwen3-8b": {"truthfulqa": 0.124569, "gsm8k": 1e9, "strategyqa": 1e9, "freshqa": 0.069722},
    "llama-3.1-8b": {"truthfulqa": 0.252106, "gsm8k": 0.185027, "strategyqa": 1e9, "freshqa": -1.0},
    "ministral-8b": {"truthfulqa": 0.298978, "gsm8k": 1e9, "strategyqa": 1e9, "freshqa": 0.258483},
}


def methods_block(ds: str, backbone: str) -> str:
    tau = TARG_TAU[backbone][ds]
    dtr_tau = DTR_TAU[backbone][ds]
    targ = "draft_tokens: 20, beta: 3.0, top_k: 5"
    dtr = ("top_n: 5, top_k: 3, ais: angle, pseudo_query_chars: 2000, embed_url: http://localhost:8300/v1, "
           "embed_model: bge-m3")   # bge-m3 embedding server: `serve.sh start embed`
    return (
        "  direct: {}\n"
        "  adaptive_rag: {max_num_sentences: 10, single_top_k: 5, ircot_top_k: 6}\n"
        "  react: {max_steps: 7, top_k: 5}\n"
        "  self_consistency: {num_samples: 5, sample_temperature: 0.7}  # k CoT samples + majority vote (k/temperature as in TRACE)\n"
        f"  targ: {{{targ}, tau: {tau}}}   # TARG (arXiv 2511.09803), margin gate\n"
        f"  targ_never: {{{targ}, force: never}}    # calibration branch\n"
        f"  targ_always: {{{targ}, force: always}}  # calibration branch\n"
        f"  dtr: {{{dtr}, tau: {dtr_tau}}}   # DTR (arXiv 2601.03908)\n"
        f"  dtr_never: {{{dtr}, force: never}}    # calibration branch\n"
        f"  dtr_always: {{{dtr}, force: always}}  # calibration branch\n"
    )


def main() -> None:
    for backbone, (served, port, extra) in BACKBONES.items():
        out = ROOT / "configs" / backbone
        (out / "baselines").mkdir(parents=True, exist_ok=True)
        for ds, (path, max_tokens) in DATASETS.items():
            run_extra = (f"\n  current_date: {CURRENT_DATE[ds]}   # benchmark date, given to every method"
                         if ds in CURRENT_DATE else "")
            (out / f"{ds}.yaml").write_text(TEMPLATE.format(
                backbone=backbone, ds=ds, served=served, port=port, extra=extra, run_extra=run_extra,
                max_tokens=max_tokens, judge=JUDGE, path=path))
            (out / "baselines" / f"{ds}.yaml").write_text(BASELINE_TEMPLATE.format(
                backbone=backbone, ds=ds, served=served, port=port, extra=extra, run_extra=run_extra,
                judge=JUDGE, path=path, methods=methods_block(ds, backbone)))
            print(out / f"{ds}.yaml", out / "baselines" / f"{ds}.yaml")


if __name__ == "__main__":
    main()
